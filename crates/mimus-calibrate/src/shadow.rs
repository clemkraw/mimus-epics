//! Checks a template against the original observations.
//!
//! This validation distinguishes an instrument from a simulator. Without
//! it, MIMUS would generate messages using assumptions made by the same
//! code that analyzed the system. Fidelity would remain unverified.
//!
//! Two independent checks cover different parts of the pipeline.
//!
//! **Structure.** Rebuild each observation by filling every slot with
//! sample `k`, then compare the result byte for byte with observation
//! `k`. This verifies that the chunks and slots account for the entire
//! message, with no missing bytes, invented bytes or incorrect boundaries.
//!
//! **Emission.** Compile the template through the emitter used to serve
//! messages, render an update, then compare every region the emitter did
//! not fill. This verifies that template compilation, chunk ordering and
//! buffer handling preserve the original fixed bytes.
//!
//! Both checks compare against data captured from a real IOC, not against
//! output generated by MIMUS.

use std::ops::Range;

use mimus_emit::{Compiled, EpicsTime};
use mimus_profile::{Chunk, Template};

/// Describes a mismatch between a template and an observation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Divergence {
    /// The rebuilt message has a different length from the observation.
    Length {
        observation: usize,
        expected: usize,
        got: usize,
    },
    /// A byte differs in a region the template should reproduce exactly.
    Byte {
        observation: usize,
        offset: usize,
        expected: u8,
        got: u8,
    },
    /// A replayable slot contains a value different from its original sample.
    ///
    /// This catches cases where a generated value overwrites a slot that
    /// should have been replayed. For example, a value slot crossing a
    /// string length prefix once received a generated double. The message
    /// length and bytes outside the slot still matched, but PVXS decoded
    /// a 106-character string from the corrupted message.
    SlotNotReplayed {
        observation: usize,
        offset: usize,
        expected: u8,
        got: u8,
    },
    /// A slot has no sample for this observation.
    MissingSample {
        observation: usize,
        slot: u16,
        samples: usize,
    },
    /// A chunk refers to a slot that is not defined in the template.
    UnknownSlot { slot: u16 },
    /// The emitter could not compile the template.
    Uncompilable { reason: String },
}

impl std::fmt::Display for Divergence {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Length {
                observation,
                expected,
                got,
            } => write!(
                f,
                "observation {observation}: rebuilt {got} bytes, the IOC sent {expected}"
            ),
            Self::Byte {
                observation,
                offset,
                expected,
                got,
            } => write!(
                f,
                "observation {observation}: byte {offset} is 0x{got:02x}, \
                 the IOC sent 0x{expected:02x}"
            ),
            Self::SlotNotReplayed {
                observation,
                offset,
                expected,
                got,
            } => write!(
                f,
                "observation {observation}: byte {offset} inside a slot is \
                 0x{got:02x}, the IOC sent 0x{expected:02x} — the slot was not \
                 replayed, and whatever wrote there may have overwritten a \
                 length or a tag"
            ),
            Self::MissingSample {
                observation,
                slot,
                samples,
            } => write!(
                f,
                "observation {observation}: slot {slot} holds {samples} sample(s)"
            ),
            Self::UnknownSlot { slot } => write!(f, "a chunk names undefined slot {slot}"),
            Self::Uncompilable { reason } => write!(f, "the emitter refused it: {reason}"),
        }
    }
}

/// Validation results with enough detail to investigate any mismatch.
#[derive(Debug, Clone, Default)]
pub struct Report {
    pub observations: usize,
    /// Total bytes verified as fixed across all observations.
    pub bytes_verified: usize,
    /// Total bytes assigned to slots and filled by the emitter at runtime.
    pub bytes_in_slots: usize,
    pub divergences: Vec<Divergence>,
}

impl Report {
    pub fn passed(&self) -> bool {
        self.divergences.is_empty()
    }

    /// Returns the fraction of message bytes represented by fixed data.
    ///
    /// This is not a quality score. A message containing mostly values
    /// can have a low fraction while being accurately described. A large
    /// opaque slot can produce the same result while leaving much of the
    /// message unexplained. This metric helps identify the latter case.
    pub fn verified_fraction(&self) -> Option<f64> {
        let total = self.bytes_verified + self.bytes_in_slots;
        (total > 0).then(|| self.bytes_verified as f64 / total as f64)
    }

    pub fn summary(&self) -> String {
        if self.passed() {
            format!(
                "{} observations reproduced exactly, {:.0}% of each message pinned to fixed bytes",
                self.observations,
                self.verified_fraction().unwrap_or(0.0) * 100.0
            )
        } else {
            format!(
                "{} divergence(s) over {} observations",
                self.divergences.len(),
                self.observations
            )
        }
    }
}

/// Rebuilds observation `k` and records the byte range occupied by each slot.
///
/// The ranges let the emission check ignore exactly the bytes the emitter
/// is allowed to modify, while still checking every fixed byte.
fn rebuild(template: &Template, k: usize) -> Result<(Vec<u8>, Vec<Range<usize>>), Divergence> {
    let mut out = Vec::new();
    let mut slots = Vec::new();
    for chunk in &template.chunks {
        match chunk {
            Chunk::Fixed { bytes } => out.extend_from_slice(bytes),
            Chunk::Slot { id } => {
                let slot = template
                    .slot(*id)
                    .ok_or(Divergence::UnknownSlot { slot: *id })?;
                let sample = slot.samples.get(k).ok_or(Divergence::MissingSample {
                    observation: k,
                    slot: *id,
                    samples: slot.samples.len(),
                })?;
                let start = out.len();
                out.extend_from_slice(sample);
                slots.push(start..out.len());
            }
        }
    }
    Ok((out, slots))
}

/// Verifies a template against the observations used to build it.
///
/// `observations` must contain the original message bodies in capture order,
/// matching the order of samples stored in the slots. Otherwise, the
/// comparison would use samples from different observations.
pub fn verify(template: &Template, observations: &[Vec<u8>]) -> Report {
    let mut report = Report {
        observations: observations.len(),
        ..Default::default()
    };

    // Check one: rebuild each observation and verify that every byte
    // is accounted for and reproduced exactly.
    let mut slot_ranges: Vec<Vec<Range<usize>>> = Vec::with_capacity(observations.len());
    for (k, obs) in observations.iter().enumerate() {
        let (rebuilt, slots) = match rebuild(template, k) {
            Ok(v) => v,
            Err(d) => {
                report.divergences.push(d);
                slot_ranges.push(Vec::new());
                continue;
            }
        };
        if rebuilt.len() != obs.len() {
            report.divergences.push(Divergence::Length {
                observation: k,
                expected: obs.len(),
                got: rebuilt.len(),
            });
            slot_ranges.push(slots);
            continue;
        }
        for (offset, (got, expected)) in rebuilt.iter().zip(obs.iter()).enumerate() {
            if got != expected {
                report.divergences.push(Divergence::Byte {
                    observation: k,
                    offset,
                    expected: *expected,
                    got: *got,
                });
                // Report only the first mismatch per observation.
                // A boundary error can shift every subsequent byte, so reporting each
                // difference adds no useful detail.
                break;
            }
        }
        let in_slots: usize = slots.iter().map(ExactSizeIterator::len).sum();
        report.bytes_in_slots += in_slots;
        report.bytes_verified += obs.len() - in_slots;
        slot_ranges.push(slots);
    }

    // Check two: compile and render the template, then verify that
    // the emitter preserves every byte it is not meant to modify.
    let compiled = match Compiled::new(template) {
        Ok(c) => c,
        Err(e) => {
            report.divergences.push(Divergence::Uncompilable {
                reason: e.to_string(),
            });
            return report;
        }
    };

    let now = EpicsTime::from_parts(0, 0);
    for (k, obs) in observations.iter().enumerate() {
        let mut rendered = Vec::with_capacity(obs.len());
        // Using step `k` selects sample `k` for replayed slots,
        // keeping the rendered message aligned with its observation.
        compiled.render(k as u64, 1, now, &mut rendered);

        if rendered.len() != obs.len() {
            report.divergences.push(Divergence::Length {
                observation: k,
                expected: obs.len(),
                got: rendered.len(),
            });
            continue;
        }

        // Every byte outside a slot must match the original observation.
        let skip = &slot_ranges[k];
        for (offset, (got, expected)) in rendered.iter().zip(obs.iter()).enumerate() {
            if skip.iter().any(|r| r.contains(&offset)) {
                continue;
            }
            if got != expected {
                report.divergences.push(Divergence::Byte {
                    observation: k,
                    offset,
                    expected: *expected,
                    got: *got,
                });
                break;
            }
        }

        // Replayable slots must also match their original samples.
        // Only slots filled live by the emitter may differ. Checking
        // this catches generated values overwriting bytes such as a
        // string length prefix, which would otherwise go unnoticed.
        let mut cursor = 0usize;
        let mut bad = None;
        for chunk in &template.chunks {
            match chunk {
                Chunk::Fixed { bytes } => cursor += bytes.len(),
                Chunk::Slot { id } => {
                    let Some(slot) = template.slot(*id) else {
                        continue;
                    };
                    let len = slot.samples.get(k).map(Vec::len).unwrap_or(0);
                    if !slot.role.needs_live_fill() {
                        for offset in cursor..cursor + len {
                            match (rendered.get(offset), obs.get(offset)) {
                                (Some(got), Some(expected)) if got != expected => {
                                    bad = Some((offset, *expected, *got));
                                    break;
                                }
                                _ => {}
                            }
                        }
                    }
                    cursor += len;
                }
            }
            if bad.is_some() {
                break;
            }
        }
        if let Some((offset, expected, got)) = bad {
            report.divergences.push(Divergence::SlotNotReplayed {
                observation: k,
                offset,
                expected,
                got,
            });
        }
    }

    report
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{build, layout};
    use mimus_profile::{Slot, SlotWidth};

    fn capture() -> Vec<Vec<u8>> {
        [
            "028203 4e2f1da0a7ca5840 e91f866a00000000 d3236009 0000000000",
            "028203 24b95bf59f585840 ea1f866a00000000 9bb86009 0000000000",
            "028203 047c4c1052a85740 eb1f866a00000000 20596309 0000000000",
            "028203 d7d473e780bb5640 ec1f866a00000000 476e5f09 0000000000",
        ]
        .iter()
        .map(|s| {
            let clean: String = s.chars().filter(|c| !c.is_whitespace()).collect();
            (0..clean.len())
                .step_by(2)
                .map(|i| u8::from_str_radix(&clean[i..i + 2], 16).unwrap())
                .collect()
        })
        .collect()
    }

    fn intro() -> Vec<u8> {
        let name = b"epics:nt/NTScalar:1.0";
        let mut v = vec![0xFF, 0xFD, 0x01, 0x00, 0x80, name.len() as u8];
        v.extend_from_slice(name);
        v
    }

    fn from_capture() -> (Vec<Vec<u8>>, Template) {
        let obs = capture();
        let pieces = layout::layout(&obs).unwrap();
        let full = intro();
        let t = build::template(
            &build::Observed {
                pv: "MIM:F64:0",
                pieces: &pieces,
                introspection_full: Some(&full),
                introspection_id_only: None,
                observations: obs.len() as u32,
            },
            "ntscalar_f64",
        )
        .unwrap();
        (obs, t)
    }

    #[test]
    fn a_template_built_from_a_real_capture_verifies() {
        let (obs, t) = from_capture();
        let r = verify(&t, &obs);
        assert!(r.passed(), "{:?}", r.divergences);
        assert_eq!(r.observations, 4);
    }

    #[test]
    fn the_report_says_how_much_is_pinned_down() {
        // Each message has eight fixed bytes: the changed-set at the front and the constant tail.
        // The remaining twenty bytes are values and timestamps stored in slots.
        let (obs, t) = from_capture();
        let r = verify(&t, &obs);
        assert_eq!(r.bytes_verified, 8 * 4);
        assert_eq!(r.bytes_in_slots, 20 * 4);
        assert!((r.verified_fraction().unwrap() - 8.0 / 28.0).abs() < 1e-9);
    }

    #[test]
    fn a_corrupted_fixed_chunk_is_caught_with_its_offset() {
        // Detects a template that claims a byte the IOC never sent.
        // Without this check, MIMUS would keep emitting the incorrect byte,
        // and consumers might decode the corrupted message without error.
        let (obs, mut t) = from_capture();
        let Chunk::Fixed { bytes } = &mut t.chunks[0] else {
            panic!("first chunk should be fixed")
        };
        bytes[1] = 0xFF;

        let r = verify(&t, &obs);
        assert!(!r.passed());
        assert!(matches!(
            r.divergences[0],
            Divergence::Byte {
                offset: 1,
                expected: 0x82,
                got: 0xFF,
                ..
            }
        ));
    }

    #[test]
    fn a_slot_boundary_off_by_one_is_caught() {
        // Shortening a slot leaves a byte outside its declared range and
        // makes the rebuilt message too short.
        //
        // This test also covers a real emitter bug: it trusted the declared
        // width and wrote an eight-byte double into a seven-byte slot,
        // overwriting the adjacent field. Compilation now rejects this
        // template, so verification catches it in both checks.
        let (obs, mut t) = from_capture();
        let slot = t.slots.iter_mut().find(|s| s.id == 1).unwrap();
        slot.width = SlotWidth::Fixed { bytes: 7 };
        for s in &mut slot.samples {
            s.pop();
        }
        let r = verify(&t, &obs);
        assert!(!r.passed(), "a shortened slot went unnoticed");
        assert!(
            r.divergences
                .iter()
                .any(|d| matches!(d, Divergence::Length { .. })),
            "a shortened slot must show up as a short message: {:?}",
            r.divergences
        );
    }

    #[test]
    fn a_slot_filled_with_something_other_than_what_was_seen_is_caught() {
        // Previously, a generated double could overwrite a value slot that
        // crossed a string length prefix. The message length and all bytes
        // outside the slots still matched, so the shadow check passed.
        // PVXS then decoded a 106-character string and closed the connection.
        //
        // Clearing the samples simulates this case by making the emitter
        // generate a value instead of replaying the captured bytes.
        let (obs, mut t) = from_capture();
        let slot = t
            .slots
            .iter_mut()
            .find(|s| matches!(s.role, mimus_profile::SlotRole::Value { .. }))
            .expect("the capture has a value slot");
        slot.samples.clear();

        let r = verify(&t, &obs);
        assert!(
            !r.passed(),
            "a generated value inside a slot went unnoticed"
        );
        assert!(
            r.divergences.iter().any(|d| matches!(
                d,
                Divergence::MissingSample { .. } | Divergence::SlotNotReplayed { .. }
            )),
            "{:?}",
            r.divergences
        );
    }

    #[test]
    fn a_missing_sample_is_reported_rather_than_skipped() {
        // Every observation must be verifiable. Silently checking only the
        // observations with available samples would hide incomplete templates.
        let (obs, mut t) = from_capture();
        t.slots.iter_mut().for_each(|s| {
            s.samples.truncate(2);
        });
        let r = verify(&t, &obs);
        assert!(!r.passed());
        assert!(
            r.divergences
                .iter()
                .any(|d| matches!(d, Divergence::MissingSample { observation: 2, .. }))
        );
    }

    #[test]
    fn a_chunk_naming_no_slot_is_reported() {
        let (obs, mut t) = from_capture();
        t.chunks.push(Chunk::Slot { id: 99 });
        let r = verify(&t, &obs);
        assert!(
            r.divergences
                .iter()
                .any(|d| matches!(d, Divergence::UnknownSlot { slot: 99 }))
        );
    }

    #[test]
    fn a_template_the_emitter_refuses_is_reported_not_ignored() {
        // An unclassified slot without samples cannot be filled. The
        // structural check reports the missing sample, and compilation
        // must also reject the invalid template.
        let mut t = Template::new("broken", 0x0D);
        t.push_fixed(vec![1, 2, 3])
            .push_slot(Slot::new(1, SlotWidth::Fixed { bytes: 2 }));
        let r = verify(&t, &[vec![1, 2, 3, 9, 9]]);
        assert!(
            r.divergences
                .iter()
                .any(|d| matches!(d, Divergence::Uncompilable { .. }))
        );
    }

    #[test]
    fn the_emission_check_ignores_only_the_slots() {
        // The emitter fills doubles from signals and timestamps from the
        // clock. Those bytes must be excluded, but all fixed bytes must
        // still be checked. Excluding anymore would weaken the check.
        let (obs, t) = from_capture();
        let r = verify(&t, &obs);
        assert!(r.passed());
        // Each message has twenty slot bytes and eight fixed bytes.
        // This confirms the check still verifies the fixed regions.
        assert_eq!(r.bytes_verified / r.observations, 8);
    }

    #[test]
    fn a_variable_length_template_verifies_too() {
        // Variable-length strings exercise the emitter's chunk-based
        // rendering path rather than a fixed-size message buffer.
        let texts = ["pos=-37.3877", "pos=1.68139", "pos=21.512", "pos=-8.30894"];
        let obs: Vec<Vec<u8>> = texts
            .iter()
            .enumerate()
            .map(|(k, text)| {
                let mut m = vec![0x02, 0x82, 0x03, text.len() as u8];
                m.extend_from_slice(text.as_bytes());
                m.extend_from_slice(&(1_787_174_889i64 + k as i64).to_le_bytes());
                m.extend_from_slice(&(157_360_595u32 + k as u32).to_le_bytes());
                m.extend_from_slice(&[0u8; 5]);
                m
            })
            .collect();

        let pieces = layout::layout(&obs).unwrap();
        let full = intro();
        let t = build::template(
            &build::Observed {
                pv: "MIM:STRV:0",
                pieces: &pieces,
                introspection_full: Some(&full),
                introspection_id_only: None,
                observations: obs.len() as u32,
            },
            "ntscalar_var",
        )
        .unwrap();

        let r = verify(&t, &obs);
        assert!(r.passed(), "{:?}", r.divergences);
    }

    #[test]
    fn the_summary_reads_as_a_verdict() {
        let (obs, t) = from_capture();
        let r = verify(&t, &obs);
        assert!(r.summary().contains("4 observations reproduced exactly"));

        let mut broken = t.clone();
        broken.chunks.push(Chunk::Slot { id: 99 });
        assert!(verify(&broken, &obs).summary().contains("divergence"));
    }

    #[test]
    fn verification_is_deterministic() {
        let (obs, t) = from_capture();
        assert_eq!(verify(&t, &obs).divergences, verify(&t, &obs).divergences);
    }
}

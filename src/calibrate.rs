//! `mimus calibrate` turns a reference IOC into a profile.
//!
//! The pipeline, in order:
//!
//! ```text
//!   channels.txt  →  observe a real softIocPVX
//!                 →  analyze each channel's bodies
//!                 →  build a template for each distinct type
//!                 →  verify the templates against their source bytes
//!                 →  write the profile, or refuse and explain why
//! ```
//!
//! The final step is the critical one. A calibration that silently produced
//! a profile from partial observations would be worse than one that failed.
//! The resulting profile would look valid, serve requests normally, and be
//! wrong in ways that downstream components could not detect.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::time::Duration;

use mimus_calibrate::build::Observed;
use mimus_calibrate::observe::{Criterion, Status, progress, status};
use mimus_calibrate::{Settings, build, layout, shadow};
use mimus_profile::{Assignment, Manifest, Profile, SessionRules, Template};
use mimus_wire::header::ByteOrder;

/// Everything the command needs.
pub struct Args {
    pub addr: String,
    pub channels: PathBuf,
    pub out: PathBuf,
    pub catalogue: Vec<PathBuf>,
    pub min_distinct: usize,
    pub settled_after: f64,
    pub deadline_s: f64,
    pub pvxs_version: String,
    pub epics_version: String,
    /// Print each step's observations, broken down by channel.
    ///
    /// Failures in this pipeline have often been invisible from the outside:
    /// a misread descriptor, a sub-command with the opposite meaning, or a
    /// status field with an unexpected width. None of these failures announced
    /// themselves, and each required another round trip to diagnose. This
    /// option prints enough detail to make that round trip unnecessary.
    pub debug: bool,
    /// Write the profile even if the acceptance criteria are not met.
    ///
    /// A partial profile can be useful during development, but is dangerous
    /// elsewhere. This option is disabled by default, reports what is missing,
    /// and records its use in the manifest so results derived from an
    /// incomplete profile can be traced back.
    pub allow_incomplete: bool,
}

/// Read a channel list: one name per line, with `#` starting a comment.
///
/// Kept deliberately simple. This is not a record list: QSRV2 exposes record
/// fields as channels in their own right, and some type codes are reachable
/// only through those fields. The list must therefore be editable by hand or
/// generated by a script, without requiring an intermediate tool.
pub fn read_channels(path: &Path) -> Result<Vec<String>, String> {
    let text = std::fs::read_to_string(path)
        .map_err(|e| format!("cannot read {}: {e}", path.display()))?;
    let mut list: Vec<String> = Vec::new();
    let mut first_line: std::collections::HashMap<String, usize> = Default::default();
    for (n, line) in text.lines().enumerate() {
        let name = line.split('#').next().unwrap_or("").trim();
        if name.is_empty() {
            continue;
        }
        // A channel listed twice would be observed twice and assigned twice,
        // and counted twice in the profile's coverage.
        if let Some(first) = first_line.insert(name.to_string(), n + 1) {
            return Err(format!(
                "{}: {name} is listed on line {first} and again on line {}",
                path.display(),
                n + 1
            ));
        }
        list.push(name.to_string());
    }
    if list.is_empty() {
        return Err(format!("{} lists no channels", path.display()));
    }
    Ok(list)
}

/// The manifest's record of the catalogue: one checksum per database, in
/// the order given, so a change to any of them shows.
fn catalogue_checksums(paths: &[PathBuf]) -> String {
    if paths.is_empty() {
        return "unspecified".to_string();
    }
    let sums: Vec<String> = paths.iter().map(|p| catalogue_checksum(p)).collect();
    if sums.iter().any(|s| s == "unavailable") {
        return "unavailable".to_string();
    }
    sums.join("+")
}

fn catalogue_checksum(path: &Path) -> String {
    // Tie a profile to the catalogue that produced it. Without a hashing
    // dependency, this records the file size and a simple checksum. It can
    // detect catalogue changes, but is not a cryptographic digest.
    match std::fs::read(path) {
        Ok(bytes) => {
            let mut h: u64 = 0xcbf29ce484222325;
            for b in &bytes {
                h ^= *b as u64;
                h = h.wrapping_mul(0x100000001b3);
            }
            format!("fnv1a64:{h:016x}:{}", bytes.len())
        }
        Err(_) => "unavailable".to_string(),
    }
}

/// Rejects options that would otherwise surface only after the calibration:
/// a deadline that cannot be a duration, a catalogue that cannot be read and
/// would be recorded as unavailable, an output that cannot be written.
fn check_options(args: &Args) -> Result<(), String> {
    if !(args.deadline_s > 0.0 && Duration::try_from_secs_f64(args.deadline_s).is_ok()) {
        return Err(format!(
            "--deadline-s: {} is not a positive number of seconds",
            args.deadline_s
        ));
    }
    if !(args.settled_after > 0.0 && args.settled_after.is_finite()) {
        return Err(format!(
            "--settled-after: {} is not a positive number of seconds",
            args.settled_after
        ));
    }
    if args.min_distinct < 2 {
        return Err(format!(
            "--min-distinct: {} is too few; telling what moves takes at least 2 distinct bodies",
            args.min_distinct
        ));
    }
    // Read each whole, as the manifest will: opening a directory succeeds.
    for path in &args.catalogue {
        if let Err(e) = std::fs::read(path) {
            return Err(format!("--catalogue: cannot read {}: {e}", path.display()));
        }
    }
    // The profile is written beside its destination first, then moved over
    // it, so both must be writable.
    crate::check_writable(&args.out).map_err(|e| format!("--out: {e}"))?;
    crate::check_writable(&partial_path(&args.out)).map_err(|e| format!("--out: {e}"))
}

pub fn run(args: Args) -> i32 {
    if let Err(e) = check_options(&args) {
        eprintln!("error: {e}");
        return 1;
    }
    let channels = match read_channels(&args.channels) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("error: {e}");
            return 1;
        }
    };

    out!("calibrating against {} ", args.addr);
    out!(
        "{} channels from {}",
        channels.len(),
        args.channels.display()
    );
    out!();

    let criterion = Criterion {
        min_distinct_updates: args.min_distinct,
        settled_after: args.settled_after,
        give_up_after: args.deadline_s,
    };
    let settings = Settings {
        deadline: Duration::from_secs_f64(args.deadline_s),
        ..Default::default()
    };

    let runtime = match tokio::runtime::Runtime::new() {
        Ok(r) => r,
        Err(e) => {
            eprintln!("error: cannot start the runtime: {e}");
            return 1;
        }
    };

    let started = std::time::Instant::now();
    let mut last_line = String::new();
    let observers = runtime.block_on(async {
        mimus_calibrate::observe(&args.addr, &channels, settings, |obs, now| {
            let p = progress(obs, &criterion, now);
            let line = format!("  {}  ({:.0}s)", p.summary(), now);
            if line != last_line {
                out!("{line}");
                last_line = line;
            }
            p.is_complete()
        })
        .await
    });

    let observers = match observers {
        Ok(o) => o,
        Err(e) => {
            eprintln!("\nerror: {e}");
            return 1;
        }
    };

    // Use the actual observation duration, not the configured deadline.
    // Evaluating channels against a clock that ran beyond the observations
    // could make every channel appear settled, regardless of its final state.
    let elapsed = started.elapsed().as_secs_f64();
    let report = progress(&observers, &criterion, elapsed);
    out!();

    if report.heard_nothing() {
        eprintln!(
            "error: the IOC answered for none of the {} channels.",
            channels.len()
        );
        eprintln!("  Check the address, and that the IOC loaded the catalogue.");
        return 1;
    }

    if !report.missing.is_empty() {
        out!(
            "{} channel(s) the IOC does not serve; they contribute nothing and \
             appear in no template:",
            report.missing.len()
        );
        for pv in report.missing.iter().take(10) {
            out!("  {pv}");
        }
        if report.missing.len() > 10 {
            out!("  ... and {} more", report.missing.len() - 10);
        }
        out!();
    }

    if !report.is_complete() && !args.allow_incomplete {
        eprintln!("calibration is incomplete, and no profile was written.");
        eprintln!();
        for (pv, s) in report.outstanding.iter().take(20) {
            let why = match s {
                Status::Silent => "never spoke".to_string(),
                Status::NoIntrospection => "sent updates but no type descriptor".to_string(),
                Status::Waiting { distinct } => {
                    format!("{distinct} distinct updates, {} wanted", args.min_distinct)
                }
                _ => "unfinished".to_string(),
            };
            eprintln!("  {pv:<28} {why}");
        }
        if report.outstanding.len() > 20 {
            eprintln!("  ... and {} more", report.outstanding.len() - 20);
        }
        for note in &report.types_without_cached_form {
            eprintln!("  {note}");
        }
        eprintln!();
        eprintln!("A partial profile serves happily and is wrong in ways nothing");
        eprintln!("downstream can detect. Give it longer, check the IOC has the");
        eprintln!("catalogue loaded, or pass --allow-incomplete knowingly.");
        // Not 2, which is what a mistyped option exits with.
        return 3;
    }

    // ---- analyze and group -------------------------------------------
    //
    // Channels with identical descriptor bytes share a template. The
    // descriptor is the wire-level definition of a type: if the protocol
    // cannot distinguish two channels by their descriptor, they belong to the same group.
    let mut by_descriptor: BTreeMap<Vec<u8>, Vec<usize>> = BTreeMap::new();
    let mut skipped: Vec<(String, String)> = Vec::new();

    // A server that caches descriptors sends each type in full once per
    // connection, and only its registry ID afterwards. The ID is what ties
    // a channel that received the short form to its type.
    let key_of_id: BTreeMap<[u8; 2], Vec<u8>> = observers
        .iter()
        .filter_map(|o| {
            let full = o.introspection_full.as_deref()?;
            Some((
                mimus_calibrate::client::descriptor_id(full)?,
                mimus_calibrate::client::descriptor_key(full),
            ))
        })
        .collect();

    for (i, o) in observers.iter().enumerate() {
        match status(o, &criterion, elapsed) {
            Status::Complete { .. } | Status::Settled { .. } => {}
            // Already reported above, as a channel the IOC does not serve.
            _ if report.missing.contains(&o.pv) => continue,
            // Asked for knowingly: a channel short of the criterion still
            // gives what it showed, if that is enough to compare, and the
            // profile is marked incomplete.
            _ if args.allow_incomplete && o.updates().len() >= 2 => {}
            _ => {
                skipped.push((o.pv.clone(), "incomplete".to_string()));
                continue;
            }
        }
        match &o.introspection_full {
            // Group by the descriptor with its registry ID blanked. PVXS
            // assigns a fresh ID to each subscription, so channels of the
            // same type differ in two bytes. Grouping by the raw bytes would
            // therefore create a separate template for every channel.
            Some(full) => by_descriptor
                .entry(mimus_calibrate::client::descriptor_key(full))
                .or_default()
                .push(i),
            None => {
                // Only the cached form arrived: another channel of the same
                // type received the full descriptor, and this one belongs
                // to that type, its updates and opening included.
                match o
                    .introspection_id_only
                    .as_deref()
                    .and_then(mimus_calibrate::client::descriptor_id)
                    .and_then(|id| key_of_id.get(&id))
                {
                    Some(key) => by_descriptor.entry(key.clone()).or_default().push(i),
                    None => skipped.push((
                        o.pv.clone(),
                        "cached descriptor of a type no channel described".to_string(),
                    )),
                }
            }
        }
    }

    // Record the descriptor forms the server actually sent. A server that
    // always sends the full descriptor requires MIMUS to do the same:
    // sending a cached ID to a client that has never received the descriptor
    // it refers to would break the subscription.
    let saw_cached = observers.iter().any(|o| o.introspection_id_only.is_some());

    // Record every changed-set observed and how often it occurred. A load
    // generator that emits only the dominant pattern leaves other decode
    // paths untested; this makes the observed patterns explicit.
    let mut changed_sets: BTreeMap<Vec<u8>, u32> = BTreeMap::new();
    for o in &observers {
        for (bitset, count) in o.changed_sets() {
            *changed_sets.entry(bitset).or_insert(0) += count;
        }
    }
    let mut changed_sets: Vec<mimus_profile::ChangedSetPattern> = changed_sets
        .into_iter()
        .map(|(bitset, count)| mimus_profile::ChangedSetPattern { bitset, count })
        .collect();
    changed_sets.sort_by(|a, b| b.count.cmp(&a.count).then(a.bitset.cmp(&b.bitset)));

    let session_rules = SessionRules {
        changed_sets,
        descriptor_policy: if saw_cached {
            mimus_profile::DescriptorPolicy::FullThenId
        } else {
            mimus_profile::DescriptorPolicy::AlwaysFull
        },
        ..Default::default()
    };
    if !saw_cached {
        out!(
            "the IOC never used the cached descriptor form; the profile records \
             AlwaysFull so MIMUS behaves the same way"
        );
        out!();
    }

    let mut profile = Profile::new(
        Manifest {
            pvxs_version: args.pvxs_version.clone(),
            epics_base_version: args.epics_version.clone(),
            catalogue_checksum: catalogue_checksums(&args.catalogue),
            host: hostname(),
            captured_at: now_rfc3339(),
            mimus_version: env!("CARGO_PKG_VERSION").to_string(),
            study_duration_s: elapsed,
            pvs_observed: observers.len() as u32,
            synthetic: false,
            // Only reachable with --allow-incomplete: without it, an
            // incomplete calibration stops above.
            incomplete: !report.is_complete(),
        },
        session_rules,
    );

    // Print an observation summary before analysis. Reporting only that
    // nothing was verified, without showing what was actually observed,
    // would hide the very failures this tool is intended to expose.
    let with_full = observers
        .iter()
        .filter(|o| o.introspection_full.is_some())
        .count();
    let with_cached = observers
        .iter()
        .filter(|o| o.introspection_full.is_none() && o.introspection_id_only.is_some())
        .count();
    let silent = observers.iter().filter(|o| o.total_updates() == 0).count();
    let too_few = observers
        .iter()
        .filter(|o| o.total_updates() > 0 && o.updates().len() < 2)
        .count();

    out!(
        "observed: {} channels, {with_full} with a full descriptor, \
         {with_cached} with a cached one, {silent} silent",
        observers.len()
    );
    out!(
        "{} distinct type descriptor(s), {too_few} channel(s) with fewer than two updates",
        by_descriptor.len()
    );
    out!();

    if args.debug {
        out!("--- channels ---");
        for o in &observers {
            let intro = match (&o.introspection_full, &o.introspection_id_only) {
                (Some(f), _) => format!("full {} B [{}]", f.len(), head(f, 10)),
                (None, Some(c)) => format!("cached {} B [{}]", c.len(), head(c, 10)),
                (None, None) => "none".to_string(),
            };
            let body = o
                .updates()
                .first()
                .map(|u| format!("{} B [{}]", u.len(), head(u, 12)))
                .unwrap_or_else(|| "-".to_string());
            out!(
                "  {:<26} {:>4} upd {:>4} distinct  {:<28} body {body}",
                o.pv,
                o.total_updates(),
                o.distinct_updates(),
                intro
            );
        }
        out!();
        out!("--- descriptor groups ---");
        for (d, members) in &by_descriptor {
            let names: Vec<&str> = members.iter().map(|i| observers[*i].pv.as_str()).collect();
            out!("  {} B [{}]  {:?}", d.len(), head(d, 12), names);
        }
        out!();
    }

    let mut namer = build::Namer::new();
    let mut verified = 0usize;
    let mut failures = 0usize;
    let mut single_update = 0usize;
    let mut frozen_openings = 0usize;

    for members in by_descriptor.values() {
        // The first channel of the type that received its full descriptor:
        // the one a caching server sent first, and the template's source.
        let Some(first) = members
            .iter()
            .map(|i| &observers[*i])
            .find(|o| o.introspection_full.is_some())
        else {
            continue;
        };

        // Use only the steady-state message shape. A monitor's first update
        // carries the complete value; subsequent updates carry deltas.
        // Diffing the two together would describe neither format correctly.
        let all_shapes = first.by_changed_set();
        let steady = first.steady_state();
        let updates: &[Vec<u8>] = &steady;
        if args.debug && all_shapes.len() > 1 {
            out!(
                "  {:<26} {} message shape(s); templating the most common",
                first.pv,
                all_shapes.len()
            );
            for (bitset, group) in &all_shapes {
                out!(
                    "      changed-set [{}]  {:>3} update(s)  {} B",
                    head(bitset, 8),
                    group.len(),
                    group.first().map(Vec::len).unwrap_or(0)
                );
            }
        }
        // A settled channel has only one body, so there is nothing to diff.
        // Its template consists entirely of fixed bytes. This is appropriate
        // for setpoints, limits, and descriptions, which are common in a
        // real facility.
        //
        // With only one observation the timestamp cannot be isolated, so
        // the template has nothing to fill. MIMUS treats such a template as
        // static: its channels send their opening message and then nothing,
        // as they did on the IOC.
        let is_static = updates.len() < 2;
        if is_static {
            single_update += 1;
        }

        let pieces = if is_static {
            vec![layout::Piece::Fixed(updates[0].clone())]
        } else {
            match layout::layout(updates) {
                Ok(p) => p,
                Err(e) => {
                    eprintln!("  {}: layout failed: {e}", first.pv);
                    failures += 1;
                    continue;
                }
            }
        };
        if args.debug {
            let slots = pieces.iter().filter(|p| p.as_slot().is_some()).count();
            out!(
                "  {:<26} {} piece(s), {slots} slot(s) from {} updates",
                first.pv,
                pieces.len(),
                updates.len()
            );
        }

        // Use the cached descriptor form from any group member that received it.
        let cached = members
            .iter()
            .find_map(|i| observers[*i].introspection_id_only.as_deref());

        // The grouping key has its registry ID blanked and must never be sent
        // on the wire. The template uses the full descriptor received by a real subscription.
        let descriptor_bytes = first
            .introspection_full
            .as_deref()
            .expect("grouped on a full descriptor");
        let name = namer.assign(&build::base_name(descriptor_bytes, &pieces));
        let template = match build::template(
            &Observed {
                pv: &first.pv,
                pieces: &pieces,
                introspection_full: Some(descriptor_bytes),
                introspection_id_only: cached,
                observations: updates.len() as u32,
            },
            name.clone(),
        ) {
            Ok(t) => t,
            Err(e) => {
                eprintln!("  build failed: {e}");
                failures += 1;
                continue;
            }
        };

        // ---- opening message ------------------------------------------
        //
        // A monitor sends one complete value when it starts, followed by
        // deltas. A single subscription provides only one complete value,
        // so it cannot be diffed against another opening from that channel.
        // Channels of the same type provide independent opening messages;
        // comparing them exposes the varying value and timestamp fields
        // without requiring additional observations.
        let openings: Vec<Vec<u8>> = members
            .iter()
            .filter_map(|i| observers[*i].first_update().cloned())
            .collect();
        let mut template = template;
        if openings.len() >= 2 {
            match layout::layout(&openings) {
                Ok(initial_pieces) => {
                    match build::template(
                        &Observed {
                            pv: &first.pv,
                            pieces: &initial_pieces,
                            introspection_full: Some(descriptor_bytes),
                            introspection_id_only: cached,
                            observations: openings.len() as u32,
                        },
                        format!("{name}_initial"),
                    ) {
                        Ok(initial) => {
                            // Verify the opening template as well. An
                            // unchecked message would undermine the guarantee
                            // that every emitted template reproduces its
                            // source bytes, even if the steady-state templates
                            // all passed verification.
                            let v = shadow::verify(&initial, &openings);
                            if v.passed() {
                                template.with_initial(initial);
                            } else {
                                eprintln!("  {name}: opening message failed the shadow check");
                                for d in v.divergences.iter().take(3) {
                                    eprintln!("    {d}");
                                }
                                failures += 1;
                            }
                        }
                        Err(e) => eprintln!("  {name}: no opening message: {e}"),
                    }
                }
                Err(e) => eprintln!("  {name}: opening messages differ in length: {e}"),
            }
        } else if !openings.is_empty() {
            // With only one channel of this type, there is no second opening
            // message to diff against. Replay the first one verbatim, including
            // its timestamp, and report that limitation explicitly.
            let mut initial = Template::new(format!("{name}_initial"), 0x0D);
            initial
                .with_introspection(mimus_profile::Introspection {
                    full: descriptor_bytes.to_vec(),
                    id_only: cached.map(<[u8]>::to_vec),
                })
                .push_fixed(openings[0].clone());
            initial.observations = 1;
            template.with_initial(initial);
            frozen_openings += 1;
        }

        // ---- shadow ---------------------------------------------------
        //
        // Reconstruct the observed updates from the template and pass one
        // through the serving emitter. Any mismatch prevents this type from
        // being included in the profile.
        let verdict = shadow::verify(&template, updates);
        if !verdict.passed() {
            eprintln!("  {name}: shadow check failed");
            for d in verdict.divergences.iter().take(5) {
                eprintln!("    {d}");
            }
            failures += 1;
            continue;
        }

        out!(
            "  {name:<28} {:>3} channels  {:>4} updates  {}{}",
            members.len(),
            updates.len(),
            verdict.summary(),
            if is_static {
                "  [static: frozen timestamp]"
            } else {
                ""
            }
        );
        verified += 1;

        // ---- the type's other updates -----------------------------------
        //
        // A channel whose alarm changes sends an update with more in its
        // changed set than the ordinary one: `alarm` as well as `value` and
        // `timeStamp`. The catalogue's MIM:ALM channels cross their limits
        // for that. Every channel of the type is searched for such updates,
        // and each other changed set seen in at least two distinct bodies is
        // templated and checked as the ordinary update was, as a variant.
        let descriptor =
            mimus_wire::pvdata::Descriptor::from_init_reply(descriptor_bytes, ByteOrder::Little)
                .ok();
        let fields = |bits: &[u8]| {
            descriptor
                .as_ref()
                .map(|d| d.changed_fields(bits))
                .unwrap_or_default()
        };
        let main_key = all_shapes
            .first()
            .map(|(k, _)| k.clone())
            .unwrap_or_default();
        template.changes = fields(&main_key);
        let mut others: BTreeMap<Vec<u8>, Vec<Vec<u8>>> = BTreeMap::new();
        for i in members {
            let o = &observers[*i];
            let opening = o.opening_changed_set();
            for (key, group) in o.by_changed_set() {
                if key == main_key || opening.as_ref() == Some(&key) {
                    continue;
                }
                let bodies = others.entry(key).or_default();
                // Distinct bodies, in the order they arrived: replayed in
                // that order, transitions follow one another as observed.
                for body in group {
                    if !bodies.contains(&body) {
                        bodies.push(body);
                    }
                }
            }
        }
        for (key, group) in others {
            let changes = fields(&key);
            let label = variant_label(&template.changes, &changes, &key);
            let vname = format!("{name}+{label}");
            if group.len() < 2 {
                if args.debug {
                    out!("    {vname:<26} seen once: nothing to compare it with, left out");
                }
                continue;
            }
            let variant = layout::layout(&group)
                .map_err(|e| e.to_string())
                .and_then(|pieces| {
                    build::template(
                        &Observed {
                            pv: &first.pv,
                            pieces: &pieces,
                            introspection_full: Some(descriptor_bytes),
                            introspection_id_only: cached,
                            observations: group.len() as u32,
                        },
                        vname.clone(),
                    )
                    .map_err(|e| e.to_string())
                });
            let mut variant = match variant {
                Ok(v) => v,
                Err(e) => {
                    eprintln!("    {vname}: left out: {e}");
                    continue;
                }
            };
            variant.changes = changes;
            let v = shadow::verify(&variant, &group);
            if !v.passed() {
                eprintln!("    {vname}: left out, the shadow check failed");
                for d in v.divergences.iter().take(3) {
                    eprintln!("      {d}");
                }
                continue;
            }
            out!(
                "    + {vname:<26}      {:>4} updates  {}",
                group.len(),
                v.summary()
            );
            template.with_variant(variant);
        }

        for i in members {
            profile.assignments.push(Assignment {
                pv: observers[*i].pv.clone(),
                template: name.clone(),
            });
        }
        profile.templates.push(template);
    }

    out!();
    if failures > 0 {
        eprintln!(
            "{failures} type(s) failed verification and were left out. A template \
             that cannot reproduce the bytes it came from is not a template."
        );
    }
    if verified == 0 {
        eprintln!("error: nothing was verified; no profile written.");
        eprintln!();
        if by_descriptor.is_empty() && skipped.iter().any(|(_, why)| why == "incomplete") {
            eprintln!("  Every channel that could have given a template was left out");
            eprintln!("  as incomplete: none met the criterion, and none showed the");
            eprintln!("  two updates a comparison needs. Give calibration longer.");
        } else if by_descriptor.is_empty() {
            eprintln!("  No channel carried a full type descriptor. Every monitor");
            eprintln!("  either failed to initialize, or only ever received the");
            eprintln!("  cached form — which names a descriptor another channel");
            eprintln!("  was supposed to receive.");
        } else if failures > 0 {
            eprintln!("  {failures} type(s) failed verification; see above.");
        }
        return 1;
    }

    // The manifest counts the channels the profile was built from, as the
    // coverage line does, not the channels asked for: a name the IOC does
    // not serve was never observed.
    profile.manifest.pvs_observed = profile.assignments.len() as u32;

    // Apply structural validation only. The stopping criterion has already
    // determined whether each channel had enough observations. Applying one
    // minimum to every template here would incorrectly reject static channels,
    // which can be fully represented by a single body.
    match profile.validate(0) {
        Ok(()) => {}
        Err(e) => {
            eprintln!("error: the profile did not validate: {e}");
            return 1;
        }
    }

    let json = match profile.to_json() {
        Ok(j) => j,
        Err(e) => {
            eprintln!("error: {e}");
            return 1;
        }
    };
    if let Err(e) = write_replacing(&args.out, &json) {
        eprintln!("error: cannot write {}: {e}", args.out.display());
        return 1;
    }

    if frozen_openings > 0 {
        out!(
            "{frozen_openings} type(s) are carried by a single channel, so their \
             opening message is replayed with its timestamp frozen. Two channels \
             per type gives the diff something to work with."
        );
    }
    if single_update > 0 {
        out!(
            "{single_update} type(s) were static: their channels will send their \
             opening message and nothing after it, as on the IOC."
        );
    }
    let weak = profile.weakly_supported(args.min_distinct as u32);
    if !weak.is_empty() {
        out!(
            "{} template(s) rest on fewer than {} updates; a field that did not \
             move during the run is frozen into them:",
            weak.len(),
            args.min_distinct
        );
        for (name, n) in weak.iter().take(8) {
            out!("  {name:<28} {n} update(s)");
        }
    }
    out!("{}", profile.coverage_summary());
    out!("written to {}", args.out.display());
    if !skipped.is_empty() {
        out!();
        out!(
            "{} channel(s) contributed nothing of their own:",
            skipped.len()
        );
        for (pv, why) in skipped.iter().take(10) {
            out!("  {pv:<28} {why}");
        }
    }
    0
}

/// Names a variant by the fields it changes beyond the ordinary update:
/// `alarm` for an alarm transition. Without the fields, by its changed set.
fn variant_label(ordinary: &[String], changes: &[String], bits: &[u8]) -> String {
    let extra: Vec<&str> = changes
        .iter()
        .filter(|f| !ordinary.contains(f))
        .map(String::as_str)
        .collect();
    if !extra.is_empty() {
        return extra.join("+");
    }
    let missing: Vec<&str> = ordinary
        .iter()
        .filter(|f| !changes.contains(f))
        .map(String::as_str)
        .collect();
    if !changes.is_empty() && !missing.is_empty() {
        return format!("without-{}", missing.join("-"));
    }
    let hex: Vec<String> = bits.iter().map(|b| format!("{b:02x}")).collect();
    format!("set-{}", hex.join(""))
}

/// Writes `text` to `path` so that the file is either the old one or the
/// new one, never a part of the new one: the text goes to a file beside it,
/// which then replaces it in one step. A profile from a previous calibration
/// therefore survives a calibration interrupted while writing.
fn write_replacing(path: &Path, text: &str) -> std::io::Result<()> {
    let partial = partial_path(path);
    std::fs::write(&partial, text)?;
    std::fs::rename(&partial, path).inspect_err(|_| {
        let _ = std::fs::remove_file(&partial);
    })
}

/// Where [`write_replacing`] puts the text before moving it over `path`.
fn partial_path(path: &Path) -> PathBuf {
    let mut partial = path.as_os_str().to_owned();
    partial.push(".partial");
    PathBuf::from(partial)
}

/// Format the first `n` bytes as hexadecimal for diagnostic output.
fn head(bytes: &[u8], n: usize) -> String {
    bytes
        .iter()
        .take(n)
        .map(|b| format!("{b:02x}"))
        .collect::<Vec<_>>()
        .join(" ")
}

fn hostname() -> String {
    std::fs::read_to_string("/proc/sys/kernel/hostname")
        .map(|s| s.trim().to_string())
        .unwrap_or_else(|_| "unknown".to_string())
}

fn now_rfc3339() -> String {
    // Record seconds since the POSIX epoch. A date library is unnecessary
    // for this single manifest timestamp; the numeric value is unambiguous.
    let secs = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs())
        .unwrap_or(0);
    format!("posix:{secs}")
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicU32, Ordering};

    /// Create a temporary file with a path unique to this test process.
    ///
    /// Naming files by process ID alone is insufficient: all tests in the
    /// same binary share that ID. Concurrent tests would then write to the
    /// same path and overwrite each other's contents. The resulting failures
    /// would depend on scheduling and could appear on one machine but not another.
    fn temp_file(label: &str, contents: &str) -> PathBuf {
        static NEXT: AtomicU32 = AtomicU32::new(0);
        let unique = NEXT.fetch_add(1, Ordering::Relaxed);
        let mut p = std::env::temp_dir();
        p.push(format!("mimus-{label}-{}-{unique}.tmp", std::process::id()));
        std::fs::write(&p, contents).expect("temp file");
        p
    }

    #[test]
    fn a_variant_is_named_by_what_it_changes_beyond_the_ordinary_update() {
        let ordinary: Vec<String> = vec!["value".into(), "timeStamp".into()];
        let with = |f: &[&str]| f.iter().map(|s| s.to_string()).collect::<Vec<_>>();
        assert_eq!(
            variant_label(
                &ordinary,
                &with(&["value", "alarm", "timeStamp"]),
                &[0xBA, 0x01]
            ),
            "alarm"
        );
        assert_eq!(
            variant_label(&ordinary, &with(&["timeStamp"]), &[0x80, 0x03]),
            "without-value"
        );
        assert_eq!(
            variant_label(&ordinary, &ordinary, &[0xC0, 0x9D]),
            "set-c09d",
            "same fields, other members: named by the set"
        );
        assert_eq!(variant_label(&[], &[], &[0x01]), "set-01");
    }

    #[test]
    fn a_channel_list_ignores_comments_and_blank_lines() {
        let p = temp_file(
            "channels",
            "# scalars\nMIM:F64:0\n\nMIM:F64:1   # two per type\n   \n#MIM:OFF\n",
        );
        assert_eq!(
            read_channels(&p).unwrap(),
            vec!["MIM:F64:0".to_string(), "MIM:F64:1".to_string()]
        );
        std::fs::remove_file(p).ok();
    }

    #[test]
    fn a_channel_list_with_crlf_endings_reads_the_same() {
        let p = temp_file("channels-crlf", "MIM:F64:0\r\nMIM:F64:1\r\n");
        assert_eq!(
            read_channels(&p).unwrap(),
            vec!["MIM:F64:0".to_string(), "MIM:F64:1".to_string()]
        );
        std::fs::remove_file(p).ok();
    }

    #[test]
    fn a_channel_listed_twice_is_refused_with_both_lines() {
        let p = temp_file("channels-dup", "MIM:F64:0\n# x\nMIM:F64:1\n  MIM:F64:0  \n");
        let e = read_channels(&p).unwrap_err();
        assert!(
            e.contains("MIM:F64:0 is listed on line 1 and again on line 4"),
            "{e}"
        );
        std::fs::remove_file(p).ok();
    }

    #[test]
    fn an_empty_list_is_an_error_rather_than_an_empty_calibration() {
        // Calibrating an empty channel list would produce an empty profile
        // that looks valid until something tries to serve from it.
        let p = temp_file("channels", "# everything commented out\n#MIM:F64:0\n");
        assert!(read_channels(&p).is_err());
        std::fs::remove_file(p).ok();
    }

    #[test]
    fn a_missing_list_names_the_file() {
        let err = read_channels(Path::new("/nonexistent/channels.txt")).unwrap_err();
        assert!(err.contains("channels.txt"), "{err}");
    }

    #[test]
    fn the_catalogue_fingerprint_changes_with_the_catalogue() {
        // The fingerprint ties a profile to the database that produced it.
        // It is not a cryptographic digest, as indicated by its prefix.
        let a = temp_file("cat", "record(calc, \"A\") {}");
        let b = temp_file("cat", "record(calc, \"B\") {}");
        let first = catalogue_checksum(&a);
        let second = catalogue_checksum(&b);
        assert!(first.starts_with("fnv1a64:"));
        assert_ne!(first, second);
        std::fs::remove_file(a).ok();
        std::fs::remove_file(b).ok();
    }

    #[test]
    fn a_profile_is_replaced_whole_and_leaves_nothing_beside_it() {
        let dir = std::env::temp_dir().join(format!("mimus-replace-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let out = dir.join("profile.json");
        std::fs::write(&out, "old").unwrap();
        write_replacing(&out, "new").unwrap();
        assert_eq!(std::fs::read_to_string(&out).unwrap(), "new");
        assert_eq!(
            std::fs::read_dir(&dir).unwrap().count(),
            1,
            "no partial file left"
        );
        std::fs::remove_dir_all(dir).ok();
    }

    #[test]
    fn every_catalogue_database_is_recorded() {
        let dir = std::env::temp_dir();
        let a = dir.join(format!("mimus-cat-a-{}.db", std::process::id()));
        let b = dir.join(format!("mimus-cat-b-{}.db", std::process::id()));
        std::fs::write(&a, b"record(ai, \"A\") {}").unwrap();
        std::fs::write(&b, b"record(ai, \"B\") {}").unwrap();
        let one = catalogue_checksums(std::slice::from_ref(&a));
        let both = catalogue_checksums(&[a.clone(), b.clone()]);
        // One database keeps the form a single checksum always had.
        assert_eq!(one, catalogue_checksum(&a));
        assert_eq!(both, format!("{one}+{}", catalogue_checksum(&b)));
        assert_eq!(catalogue_checksums(&[]), "unspecified");
        std::fs::remove_file(&b).ok();
        assert_eq!(catalogue_checksums(&[a.clone(), b]), "unavailable");
        std::fs::remove_file(a).ok();
    }

    #[test]
    fn a_missing_catalogue_is_recorded_as_unavailable_not_faked() {
        assert_eq!(
            catalogue_checksum(Path::new("/nonexistent/catalogue.db")),
            "unavailable"
        );
    }

    fn args(out: PathBuf) -> Args {
        Args {
            addr: "127.0.0.1:5075".into(),
            channels: PathBuf::from("channels.txt"),
            out,
            catalogue: Vec::new(),
            min_distinct: 30,
            settled_after: 30.0,
            deadline_s: 600.0,
            pvxs_version: "unknown".into(),
            epics_version: "unknown".into(),
            debug: false,
            allow_incomplete: false,
        }
    }

    #[test]
    fn options_that_would_fail_late_are_refused_before_connecting() {
        let out = std::env::temp_dir().join(format!("mimus-out-{}.json", std::process::id()));
        assert!(check_options(&args(out.clone())).is_ok());
        assert!(!out.exists(), "the check leaves no empty profile behind");

        for bad in [-1.0, 0.0, f64::NAN, f64::INFINITY, 1e300] {
            let mut a = args(out.clone());
            a.deadline_s = bad;
            assert!(check_options(&a).is_err(), "deadline {bad}");
            let mut a = args(out.clone());
            a.settled_after = bad;
            assert_eq!(check_options(&a).is_err(), bad != 1e300, "settled {bad}");
        }
        let mut a = args(out.clone());
        a.min_distinct = 1;
        assert!(check_options(&a).is_err());
        let mut a = args(out.clone());
        a.catalogue = vec![PathBuf::from("/nonexistent/catalogue.db")];
        assert!(check_options(&a).is_err());
        a.catalogue = vec![std::env::temp_dir()];
        assert!(check_options(&a).is_err(), "a directory is not a catalogue");
        assert!(check_options(&args(PathBuf::from("/nonexistent/profile.json"))).is_err());
    }

    #[test]
    fn concurrent_temp_files_do_not_collide() {
        // The property this helper exists for: a process ID alone would give
        // every test in this binary the same path.
        let a = temp_file("collide", "first");
        let b = temp_file("collide", "second");
        assert_ne!(a, b);
        assert_eq!(std::fs::read_to_string(&a).unwrap(), "first");
        assert_eq!(std::fs::read_to_string(&b).unwrap(), "second");
        std::fs::remove_file(a).ok();
        std::fs::remove_file(b).ok();
    }
}
